"""Combine per-chunk extraction objects into one record (BUG-05).

Two strategies, in order of preference:

1. ``synthesize_extractions`` - one final model call that receives every
   chunk's draft record plus the opening and closing sections of the source
   and returns ONE record. This is the only path that can reconcile a
   problem statement in chunk 1 with a Limitations section in chunk 14.

2. ``merge_extractions`` - deterministic fallback when the synthesis call
   fails. It now returns the single most coherent chunk record whole. The
   previous behaviour (concatenate five descriptions, take the highest
   likelihood x impact block from any chunk, product name from the first
   chunk that had one) produced records whose title came from one section
   and whose severity rationale came from another (dev R-03, R-04, R-06,
   R-07 on 24 Oct 2026). Fields are never mixed across chunks any more.
"""

from __future__ import annotations

import json
import logging
from typing import Any, Callable, Optional

logger = logging.getLogger("airisk")

# How much of the source the synthesis call sees verbatim, in addition to the
# chunk drafts. Head covers abstract + introduction; tail covers discussion,
# limitations and conclusion. 12k + 12k chars is ~7k tokens.
SYNTHESIS_HEAD_CHARS = 12_000
SYNTHESIS_TAIL_CHARS = 12_000

# Per-draft fields handed to the synthesis call. Everything else (controls,
# self-assessment) is regenerated by the final call.
_DRAFT_RISK_FIELDS = (
    "risk_title",
    "domains",
    "primary_risk",
    "secondary_risks",
    "description",
    "attack_vector",
    "observable_indicators",
    "source_type",
    "evidence_type",
    "demonstrated_finding",
    "stated_implication",
    "paper_stance",
    "proposed_mitigation",
    "mitigations_in_source",
    "ai_product_name",
    "ai_product_vendor",
)

SYNTHESIS_RULES = """
=== SYNTHESIS TASK (read before the input) ===

The INPUT below is not an article. It contains:
  (a) the OPENING of one source document (title, abstract, introduction),
  (b) the CLOSING of the same document (discussion, limitations, conclusion),
  (c) DRAFT RECORDS produced from consecutive sections of that document.

Produce ONE final record for the document as a whole, following every rule
above. In addition:
- Choose the single primary risk that the document as a whole documents.
  The drafts from the opening sections usually state it; drafts from the
  methods, results or appendix sections often describe something narrower.
- mitigations_in_source must list every safeguard, validation, limitation
  or mitigation that ANY draft or the CLOSING section describes. Only write
  "not described in source" when none of them mention one.
- evidence_type, demonstrated_finding and stated_implication must reflect
  the document's actual results, which the CLOSING section summarises.
- likelihood_reasoning and impact_reasoning must each quote a phrase that
  appears verbatim in the OPENING or CLOSING text given here.
- Do not combine claims from different drafts into one risk. Do not carry
  over any claim that comes from a cited work rather than this document.
- Severity: if the drafts disagree, follow the evidence rules, not the
  highest draft.
"""


def _coerce_int(value: object, default: int = 0) -> int:
    try:
        return int(value)  # type: ignore[arg-type]
    except (TypeError, ValueError):
        return default


def _self_assessment_rank(sa: dict[str, Any]) -> tuple[int, int, int]:
    total = _coerce_int(sa.get("total_score"), 0)
    sub_sum = (
        _coerce_int(sa.get("context_clarity_score"), 0)
        + _coerce_int(sa.get("keyword_score"), 0)
        + _coerce_int(sa.get("tagging_accuracy_score"), 0)
        + _coerce_int(sa.get("evidence_strength_score"), 0)
    )
    reasoning_count = sum(
        1
        for key in (
            "context_clarity_reasoning",
            "keyword_reasoning",
            "tagging_reasoning",
            "evidence_reasoning",
        )
        if str(sa.get(key) or "").strip()
    )
    effective_total = total if total > 0 else sub_sum
    return (effective_total, sub_sum, reasoning_count)


def _is_stub(obj: dict[str, Any]) -> bool:
    if obj.get("_source") == "stub":
        return True
    title = str((obj.get("risk") or {}).get("risk_title") or "").strip()
    return title in {"Failed Risk Extraction", "AI Risk Extraction Fallback"}


def pick_most_coherent(objs: list[dict[str, Any]]) -> dict[str, Any]:
    """Return the one chunk record with the best self-assessment, unchanged.

    Earlier chunks win ties: the opening of a paper states the problem the
    paper is about, later chunks describe narrower results.
    """
    if not objs:
        raise ValueError("no extractions to merge")
    best: dict[str, Any] | None = None
    best_rank: tuple[int, int, int] = (-1, -1, -1)
    for obj in objs:
        if _is_stub(obj):
            continue
        sa = (obj.get("justification") or {}).get("self_assessment")
        rank = _self_assessment_rank(sa) if isinstance(sa, dict) else (0, 0, 0)
        if rank > best_rank:
            best_rank = rank
            best = obj
    return best if best is not None else objs[0]


def merge_extractions(objs: list[dict[str, Any]]) -> dict[str, Any]:
    """Deterministic fallback: one whole chunk record, no cross-chunk mixing."""
    if not objs:
        raise ValueError("no extractions to merge")
    if len(objs) == 1:
        return objs[0]
    chosen = dict(pick_most_coherent(objs))
    meta = dict(chosen.get("_meta") or {})
    meta["merged_from"] = len(objs)
    meta["merge_strategy"] = "most_coherent_chunk"
    chosen["_meta"] = meta
    return chosen


def _draft_summary(index: int, obj: dict[str, Any]) -> dict[str, Any]:
    risk = obj.get("risk") or {}
    scoring = obj.get("risk_scoring") or {}
    return {
        "draft": index,
        "risk": {k: risk.get(k) for k in _DRAFT_RISK_FIELDS if k in risk},
        "risk_scoring": {
            "likelihood": scoring.get("likelihood"),
            "likelihood_reasoning": scoring.get("likelihood_reasoning"),
            "impact": scoring.get("impact"),
            "impact_reasoning": scoring.get("impact_reasoning"),
        },
    }


def build_synthesis_input(
    objs: list[dict[str, Any]],
    source_text: str,
    *,
    head_chars: int = SYNTHESIS_HEAD_CHARS,
    tail_chars: int = SYNTHESIS_TAIL_CHARS,
) -> str:
    from app.extraction.preprocess import head_and_tail

    head, tail = head_and_tail(source_text, head_chars, tail_chars)
    drafts = [
        _draft_summary(i, o) for i, o in enumerate(objs, 1) if not _is_stub(o)
    ]
    parts = [
        "=== OPENING OF SOURCE DOCUMENT ===",
        head.strip(),
    ]
    if tail.strip():
        parts += ["", "=== CLOSING OF SOURCE DOCUMENT ===", tail.strip()]
    parts += [
        "",
        f"=== DRAFT RECORDS FROM {len(drafts)} CONSECUTIVE SECTIONS ===",
        json.dumps(drafts, ensure_ascii=False, indent=1),
    ]
    return "\n".join(parts)


def synthesize_extractions(
    objs: list[dict[str, Any]],
    source_text: str,
    *,
    generate_json: Callable[..., dict[str, Any]],
    schema: dict[str, Any],
    base_system_prompt: str,
    title: str = "",
    source_url: str = "",
) -> Optional[dict[str, Any]]:
    """One final model call over the chunk drafts. Returns None on failure.

    The caller keeps the deterministic fallback; this function never raises.
    """
    live = [o for o in objs if not _is_stub(o)]
    if not live:
        return None
    if len(live) == 1:
        return live[0]
    try:
        synthesis_input = build_synthesis_input(live, source_text)
        system_prompt = base_system_prompt.rstrip() + "\n" + SYNTHESIS_RULES
        final = generate_json(
            synthesis_input,
            schema,
            title=title,
            url=source_url,
            system_prompt_override=system_prompt,
        )
        if not isinstance(final, dict) or _is_stub(final):
            logger.warning("SYNTHESIS: model returned stub; using fallback merge")
            return None
        meta = dict(final.get("_meta") or {})
        meta["merged_from"] = len(objs)
        meta["merge_strategy"] = "synthesis_call"
        final["_meta"] = meta
        return final
    except Exception as exc:  # pragma: no cover - defensive, caller falls back
        logger.warning("SYNTHESIS: call failed (%s); using fallback merge", str(exc)[:150])
        return None
